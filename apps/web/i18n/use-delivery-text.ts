type Key = (typeof entries)[number][1];
const keys: ReadonlyMap<string, Key> = new Map<string, Key>(entries);

export function useDeliveryText() {
  const t = useTranslations();
  const shared = useDomainText();
  function text(value: string): string;
  function text(value: undefined): undefined;
  function text(value: string | undefined): string | undefined;
  function text(value: string | undefined): string | undefined {
    if (value === undefined || value === '') return value;
    const key = keys.get(value);
    return key ? t(key) : shared(value);
  }
  return text;
}
